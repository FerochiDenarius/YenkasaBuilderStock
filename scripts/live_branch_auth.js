const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9222');
  const page = browser.contexts()[0].pages()[0];
  const snap = name => page.screenshot({ path: `Validation Reports/${name}`, fullPage: true });
  await page.locator('.setup-subnav button', { hasText: 'Branches' }).click();
  await page.getByTestId('branch-add-new').click();
  await page.getByTestId('branch-name').fill('Live Oyarifa Branch');
  await page.getByTestId('branch-code').fill('LIV');
  await page.getByTestId('branch-location').fill('Oyarifa, Accra');
  await page.getByTestId('branch-phone').fill('0243456789');
  await page.getByTestId('branch-email').fill('live.oyarifa@example.com');
  await page.getByTestId('branch-manager').fill('Live Branch Manager');
  await page.getByTestId('branch-managerContact').fill('0543219876');
  await snap('05_branch_live_details.png');
  await page.getByRole('button', { name: 'Continue to Login Setup' }).click();
  await page.getByTestId('branch-managerUsername').fill('live.manager');
  await page.getByTestId('branch-managerPassword').fill('LivePass123');
  await page.getByTestId('branch-confirmPassword').fill('LivePass123');
  await page.getByTestId('branch-deviceName').fill('LIVE-PC-01');
  await snap('06_branch_live_login_setup.png');
  await page.getByRole('button', { name: 'Continue to Permissions' }).click();
  await snap('07_branch_live_permissions.png');
  await page.getByTestId('branch-create-final').click();
  await page.waitForTimeout(500);
  console.log('created page contains branch', (await page.locator('body').innerText()).includes('Live Oyarifa Branch'));
  await snap('08_branch_live_created.png');
  await page.locator('.setup-subnav button', { hasText: 'Branch Login' }).click();
  await page.waitForTimeout(250);
  console.log('prelogin shell', { sidebar: await page.locator('.dashboard-sidebar').count(), hero: await page.locator('.branch-login-hero').count(), branchOps: (await page.locator('.dashboard-nav').innerText()).includes('Branch Operations') });
  await snap('09_branch_login_before.png');
  await page.getByTestId('login-role').selectOption('BRANCH_MANAGER');
  await page.getByTestId('login-username').fill('live.manager');
  await page.getByTestId('login-password').fill('wrong-password');
  await page.getByTestId('branch-login-submit').click();
  console.log('wrong login', await page.getByRole('alert').innerText());
  await page.getByTestId('login-password').fill('LivePass123');
  await page.getByTestId('branch-login-submit').click();
  await page.waitForTimeout(400);
  console.log('manager after login', { branchOps: (await page.locator('.dashboard-nav').innerText()).includes('Branch Operations'), loginVisible: await page.locator('.setup-subnav button', { hasText: 'Branch Login' }).count(), workspace: await page.locator('.branch-home').count() });
  await snap('10_branch_login_manager.png');
  await page.locator('.dashboard-shell .user-card').click();
  await page.waitForTimeout(250);
  console.log('after logout', { loginVisible: await page.locator('.setup-subnav button', { hasText: 'Branch Login' }).count(), branchOps: (await page.locator('.dashboard-nav').innerText()).includes('Branch Operations') });
  await snap('11_branch_login_after_logout.png');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
