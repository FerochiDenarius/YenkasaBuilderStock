const { chromium } = require('playwright');
const { execFile } = require('node:child_process');

(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9222');
  const page = browser.contexts()[0].pages().find((candidate) => candidate.url().includes('5173'));
  if (!page) throw new Error('Renderer page not found');
  page.setDefaultTimeout(10000);
  await page.evaluate(() => sessionStorage.removeItem('yenkasa-session'));
  await page.reload();
  await page.locator('.branch-login-nav').click();
  await page.getByTestId('login-role').selectOption('BRANCH_MANAGER');
  await page.getByTestId('login-username').fill('validation.manager');
  await page.getByTestId('login-password').fill('ValidationPass123');
  await page.getByTestId('branch-login-submit').click();
  await page.getByRole('button', { name: 'Sales & Invoices' }).click();
  await page.locator('.sales-product-card').first().waitFor();
  const internalTitleCount = await page.locator('.sales-title-row').count();
  const saleTabCount = await page.getByRole('tab', { name: 'Sale', exact: true }).count();
  const quotationTabCount = await page.getByRole('tab', { name: 'Quotation', exact: true }).count();
  const invoiceTabCount = await page.getByRole('tab', { name: 'Invoice', exact: true }).count();
  const historyTabCount = await page.getByRole('tab', { name: 'Invoice History', exact: true }).count();
  await page.getByRole('tab', { name: 'Invoice', exact: true }).click();
  await page.getByRole('button', { name: /Clear Cart/ }).click();
  await page.locator('.sales-product-card').first().click();
  const quantityInput = page.locator('.quantity-control input').first();
  await quantityInput.fill('7');
  const typedQuantity = await quantityInput.inputValue();
  await page.locator('.sales-actions .primary-button').click();
  await page.getByText(/saved to SQLite/).waitFor();
  const errors = await page.locator('.sales-error').allTextContents();
  const preview = await page.getByRole('dialog', { name: 'Invoice preview' }).count();
  const nativePrintBridge = await page.evaluate(() => typeof window.desktopBridge?.print === 'function');
  const dismissPrintDialog = new Promise((resolve) => {
    execFile('osascript', ['-e', 'delay 2', '-e', 'tell application "System Events" to key code 53'], { timeout: 10000 }, () => resolve());
  });
  const nativePrintResult = await page.evaluate(() => window.desktopBridge?.print() ?? false);
  await dismissPrintDialog;
  await page.screenshot({ path: 'Validation Reports/48_sales_cart_reconciliation_live.png', fullPage: true });
  await page.getByRole('button', { name: 'Close preview' }).click();
  await page.getByRole('tab', { name: 'Invoice History', exact: true }).click();
  await page.locator('.sales-history-panel').waitFor();
  await page.locator('.sales-history-row').first().waitFor();
  const historyRows = await page.locator('.sales-history-row').count();
  await page.screenshot({ path: 'Validation Reports/52_sales_invoice_history_live.png', fullPage: true });
  console.log('typed quantity accepted', typedQuantity === '7');
  console.log('initial cart invoice generated', errors.length === 0 && preview === 1);
  console.log('duplicate title removed', internalTitleCount === 0);
  console.log('sales tab removed', saleTabCount === 0);
  console.log('quotation/invoice/history tabs present', quotationTabCount === 1 && invoiceTabCount === 1 && historyTabCount === 1);
  console.log('invoice history loaded', historyRows > 0);
  console.log('native print bridge available', nativePrintBridge);
  console.log('native print invocation returned boolean', typeof nativePrintResult === 'boolean');
  console.log('errors', errors);
  await browser.close();
  if (errors.length || preview !== 1 || typedQuantity !== '7' || internalTitleCount !== 0 || saleTabCount !== 0 || quotationTabCount !== 1 || invoiceTabCount !== 1 || historyTabCount !== 1 || historyRows === 0 || !nativePrintBridge || typeof nativePrintResult !== 'boolean') process.exit(1);
})().catch((error) => {
  console.error(error);
  process.exit(1);
});
